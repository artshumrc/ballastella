// What a Sync does with a file that changed on both sides: a second copy, or one question (ADR-0046).
//
// ─────────────────────────────────────────────────────────────────────────────────────────────
// BOTH VERSIONS SURVIVE, AND NEITHER IS MERGED
//
// Ballastella will not combine two GeoJSON annotation sets or two Alignments of one sheet: the
// result is a document neither scholar wrote (ADR-0014). What it does instead is make sure the
// scholar can *look* at both, and then delete one — which is a scholarly judgement and theirs.
//
// So a Conflict is resolved by preserving the Remote's version beside the author's, at a path of its
// own, and letting the author's version stand where it was. The Baseline then advances at the
// contested path to the Remote's blob: this Workspace has now taken GitHub's version in, so what is
// left is an ordinary *outbound* change, and the next send puts the author's copy and the second copy
// on the Remote together. That is what makes both machines end up looking at the same pair.
//
// ─────────────────────────────────────────────────────────────────────────────────────────────
// AT THE COARSEST CONTESTED UNIT, AND THAT IS THE RULE THAT KEEPS IT READABLE
//
//   `<project>/annotations/<layer>.geojson`  → another Layer in that Project, `(from GitHub)`
//   `<project>/project.json`                 → another Project directory, `(from GitHub)`, off the
//                                              Front Page — and its Layers do **not** also double
//   `alignments/<image>.json`                → nothing at all; the author is asked which to keep
//
// A Project with three contested Layers and a contested manifest would otherwise yield a duplicate
// Project *and* three duplicate Layers, and the scholar would have six things to read where two
// would have done.
//
// ⚠ **The Alignment is the exception and the exception is the point.** There is exactly one
// Alignment per Map Image, keyed by the image's id (ADR-0023), so a second file at
// `alignments/<image-id> (from GitHub).json` is referenced by nothing and drawn nowhere. A copy the
// scholar cannot look at is worse than a question, so the question is asked instead — with each
// side's Control Point count and date, which is everything needed to answer it without opening both.
//
// ⚠ **Tiles and the site record are not here because they cannot be contested.** `images/**` and
// `base-map/tiles/**` are written once at ingest and never edited; `ballastella-site.json` is
// regenerated by every Sync. Anything else that somehow arrives contested is left exactly as it is
// on both sides rather than given an invented rule.

