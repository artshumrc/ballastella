#!/usr/bin/env node
// ADR-0034: nothing in `packages/ui` may import from `apps/`.
//
// A shared package that reaches back into a consumer is not shared — it is one app's directory with
// a second app compiling half of it. The failure is not loud: the editor keeps building, because the
// import resolves there; it is the *viewer* that breaks, or worse, quietly grows the editor's
// dependencies. So the seam is a fence rather than a convention.
//
// **Three spellings reach an app, and all three are refused.**
//
//   1. Its package name — `@ballastella/editor`, `@ballastella/viewer`. Read out of `apps/*` rather
//      than written here, so an app renamed or added cannot slip past a hardcoded list.
//   2. A relative path climbing out of the package into `apps/` — `../../apps/editor/src/…`.
//   3. **A SvelteKit alias**, `$lib` or `$app/*`. These are the likeliest spelling by a distance,
//      because they are what every component in this repository is written with today and what a
//      contributor moving one here will carry along by hand. Neither exists outside an app: `$lib`
//      is one app's `src/lib` and `$app/paths` is generated by its build. A module here that reached
//      for either would resolve to whichever consumer compiled it, which is the defect in its purest
//      form — two apps, two different modules, one file.
//
// The manifest is checked too: a `@ballastella/editor` dependency is the same claim made in a place
// no import scan would look.
//
// **It fails if it finds nothing to guard.** A fence that passes whatever the code does is worse
// than no fence, because it is read as evidence — and a scanner's way of going vacuous is silent,
// since a pattern that matches nothing and a tree with nothing to match print the same line. So: the
// package must exist and contain source, the app names must have been found, and the patterns are
// run against specimens of what they exist to catch before the scan starts.

import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PACKAGE = 'packages/ui';
const packageRoot = path.join(repoRoot, PACKAGE);

const problems = [];

/** Every app's package name, read from `apps/*` so a rename cannot leave this list stale. */
function appPackageNames() {
	const appsRoot = path.join(repoRoot, 'apps');
	if (!existsSync(appsRoot)) return [];
	return readdirSync(appsRoot, { withFileTypes: true })
		.filter((entry) => entry.isDirectory())
		.map((entry) => path.join(appsRoot, entry.name, 'package.json'))
		.filter((file) => existsSync(file))
		.map((file) => JSON.parse(readFileSync(file, 'utf8')).name)
		.filter((name) => typeof name === 'string');
}

const appNames = appPackageNames();

/**
 * Every module specifier in `text`, whatever syntax carried it.
 *
 * Static and dynamic `import`, re-`export … from`, and CSS's own `@import` — the last because the
 * shared stylesheet is a module of this package as much as a component is, and `@import` is how it
 * would reach an app's.
 */
function specifiersIn(text) {
	const found = [];
	const patterns = [
		/\bimport\s+[^'"();]*?\bfrom\s*['"]([^'"]+)['"]/g,
		/\bexport\s+[^'"();]*?\bfrom\s*['"]([^'"]+)['"]/g,
		/\bimport\s*['"]([^'"]+)['"]/g,
		/\bimport\s*\(\s*['"]([^'"]+)['"]\s*\)/g,
		/@import\s*(?:url\()?\s*['"]([^'"]+)['"]/g
	];
	for (const pattern of patterns) {
		pattern.lastIndex = 0;
		let match;
		while ((match = pattern.exec(text)) !== null) found.push(match[1]);
	}
	return found;
}

/** Why `specifier` reaches an app, or `null`. The scan and the positive control share it. */
function violationIn(specifier) {
	if (appNames.some((name) => specifier === name || specifier.startsWith(`${name}/`))) {
		return 'names an app package';
	}
	if (/(^|\/)apps\//.test(specifier)) return 'reaches into apps/ by path';
	if (specifier === '$lib' || specifier.startsWith('$lib/')) {
		return "uses $lib, which is one app's src/lib and does not exist here";
	}
	if (specifier === '$app' || specifier.startsWith('$app/')) {
		return "uses $app, which SvelteKit generates inside an app's build";
	}
	return null;
}

// ── Positive control ──────────────────────────────────────────────────────────────────────────

const KNOWN_BAD = [
	'@ballastella/editor',
	'@ballastella/viewer/src/lib/theme.svelte.js',
	'../../apps/editor/src/lib/layers/layer-kind-style.js',
	'$lib',
	'$lib/base-map/opening-view',
	'$app/paths'
];

const KNOWN_GOOD = [
	'@ballastella/core',
	'@ballastella/core/render',
	'svelte',
	'./BaseMapSwitcher.svelte',
	'../layout.css',
	// Not an app: a package whose name merely begins the same way, and a path with `apps` in a
	// segment of its own. Refusing these would train everybody to reach for an exception.
	'@ballastella/core-apps',
	'./mapps/index.js'
];

for (const specifier of KNOWN_BAD) {
	if (violationIn(specifier) === null) {
		problems.push(`this check no longer refuses \`${specifier}\`, which reaches an app`);
	}
}
for (const specifier of KNOWN_GOOD) {
	const why = violationIn(specifier);
	if (why !== null) {
		problems.push(`this check now refuses \`${specifier}\`, which is legitimate (${why})`);
	}
}
// And the extraction has to actually extract, or every specimen above is checked and no real file is.
for (const { source, expect } of [
	{ source: "import Thing from '$lib/Thing.svelte';", expect: '$lib/Thing.svelte' },
	{ source: "export { x } from '@ballastella/editor';", expect: '@ballastella/editor' },
	{ source: "import '@ballastella/core/test-fence';", expect: '@ballastella/core/test-fence' },
	{ source: "const m = await import('$app/paths');", expect: '$app/paths' },
	{ source: "@import '@ballastella/ui/layout.css';", expect: '@ballastella/ui/layout.css' }
]) {
	if (!specifiersIn(source).includes(expect)) {
		problems.push(`an import spelled \`${source}\` is no longer seen by this check`);
	}
}

if (appNames.length === 0) {
	problems.push(
		'no app package names were found under apps/, so the first and most direct spelling of this ' +
			'violation is not being checked for at all.'
	);
}

// ── The scan ──────────────────────────────────────────────────────────────────────────────────

const files = existsSync(packageRoot) ? walk(packageRoot) : [];

if (files.length === 0) {
	problems.push(
		`${PACKAGE} has no source files this check can read, so it inspected nothing. If the shared ` +
			`package has been renamed or removed, change this check in the same commit rather than ` +
			`leaving it passing over an absence.`
	);
}

const violations = [];

for (const absolute of files) {
	const relative = path.relative(repoRoot, absolute).split(path.sep).join('/');
	const lines = readFileSync(absolute, 'utf8').split('\n');
	lines.forEach((line, index) => {
		for (const specifier of specifiersIn(line)) {
			const why = violationIn(specifier);
			if (why !== null) violations.push({ file: relative, line: index + 1, specifier, why });
		}
	});
}

// The manifest says the same thing in a place no import scan would look.
{
	const manifestFile = path.join(packageRoot, 'package.json');
	if (existsSync(manifestFile)) {
		const manifest = JSON.parse(readFileSync(manifestFile, 'utf8'));
		for (const field of ['dependencies', 'devDependencies', 'peerDependencies']) {
			for (const name of Object.keys(manifest[field] ?? {})) {
				if (appNames.includes(name)) {
					violations.push({
						file: `${PACKAGE}/package.json`,
						line: 0,
						specifier: `${field}.${name}`,
						why: 'declares an app as a dependency of the shared package'
					});
				}
			}
		}
	}
}

if (violations.length > 0) {
	console.error(`\nSomething in ${PACKAGE} reaches back into an app (ADR-0034).\n`);
	for (const { file, line, specifier, why } of violations) {
		console.error(`  ${file}${line > 0 ? `:${line}` : ''}  ${specifier} — ${why}`);
	}
	console.error(
		`\n${PACKAGE} is compiled by both apps. A module here that imports from one of them is a\n` +
			'module whose meaning depends on which app compiled it, which is not a shared component\n' +
			'but a copy with extra steps. Move what is needed into this package or into\n' +
			'@ballastella/core, or pass it in as a prop.\n'
	);
}

if (problems.length > 0) {
	console.error('\nThis check is not inspecting what it claims to (ADR-0034).\n');
	for (const problem of problems) console.error(`  ${problem}\n`);
}

if (violations.length > 0 || problems.length > 0) process.exit(1);

console.log(
	`${PACKAGE}: nothing imports from apps/ — ${files.length} files scanned against ` +
		`${appNames.length} app package names (${appNames.join(', ')}), $lib and $app (ADR-0034).`
);

/** @param {string} directory @returns {string[]} */
function walk(directory) {
	let entries;
	try {
		entries = readdirSync(directory);
	} catch {
		return [];
	}
	return entries.flatMap((entry) => {
		if (entry === 'node_modules') return [];
		const absolute = path.join(directory, entry);
		if (statSync(absolute).isDirectory()) return walk(absolute);
		return /\.(ts|js|mjs|svelte|css)$/.test(entry) ? [absolute] : [];
	});
}
